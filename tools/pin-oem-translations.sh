#!/usr/bin/env bash
# Pins the car app translations that modehelper may install: one commit of
# SuspiciousRepair/integration-oem-translations and the SHA-256 of each file
# it lists. Writes modehelper/src/com/geely/modehelper/OemTextPins.java.
#
# The helper downloads only from that commit and refuses any file whose hash
# differs, so a hijacked repo, account or CDN cannot change what a car gets.
# New text reaches cars with the next Drive Assist release that carries new
# pins.
#
# usage: tools/pin-oem-translations.sh <path to integration-oem-translations> [commit]
set -euo pipefail
cd "$(dirname "$0")/.."
repo=${1:?usage: $0 <path to integration-oem-translations> [commit]}
commit=$(git -C "$repo" rev-parse "${2:-HEAD}^{commit}")
raw="https://raw.githubusercontent.com/SuspiciousRepair/integration-oem-translations/$commit"
out=modehelper/src/com/geely/modehelper/OemTextPins.java

files=$(git -C "$repo" show "$commit:manifest.json" | python3 -c '
import json, sys
m = json.load(sys.stdin)
print("manifest.json")
for a in m["apps"]: print(a["file"])')

rows=""
for f in $files; do
  local_sha=$(git -C "$repo" show "$commit:$f" | sha256sum | cut -c1-64)
  # The car downloads it from GitHub: the commit must be there, with the same bytes.
  web_sha=$(curl -fsSL "$raw/$f" | sha256sum | cut -c1-64) || { echo "not on GitHub: $raw/$f" >&2; exit 1; }
  [ "$local_sha" = "$web_sha" ] || { echo "GitHub serves other bytes for $f" >&2; exit 1; }
  rows+="        { \"$f\", \"$local_sha\" },"$'\n'
  echo "pinned $f $local_sha"
done

cat > "$out" <<JAVA
package com.geely.modehelper;

/** The car app translations this helper may install. GENERATED by
 * tools/pin-oem-translations.sh: do not edit by hand.
 *
 * {@link OemText} downloads only from {@link #COMMIT} of the
 * integration-oem-translations repo and refuses a file whose SHA-256 is not
 * the one here. */
final class OemTextPins {
    private OemTextPins() {}

    static final String COMMIT = "$commit";

    /** {path in the repo, SHA-256 of its bytes}. */
    static final String[][] FILES = {
${rows}    };
}
JAVA
echo "wrote $out (commit $commit)"
